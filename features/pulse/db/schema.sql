-- Pulse schema. Run once in the Supabase SQL editor.

create table if not exists public.services (
  id text primary key,
  name text not null,
  url text not null,
  state text not null default 'OPERATIONAL'
    check (state in ('OPERATIONAL', 'DEGRADED', 'OUTAGE')),
  latency_ms integer not null default 0,
  grade text not null default 'F'
    check (grade in ('A', 'B', 'C', 'D', 'F')),
  last_checked_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.health_logs (
  id bigint generated by default as identity primary key,
  service_id text not null references public.services (id) on delete cascade,
  ok boolean not null,
  latency_ms integer not null,
  grade text not null,
  checked_at timestamptz not null default now()
);

create index if not exists health_logs_service_checked_idx
  on public.health_logs (service_id, checked_at desc);

create table if not exists public.incidents (
  id uuid primary key default gen_random_uuid(),
  service_id text not null references public.services (id) on delete cascade,
  severity text not null check (severity in ('critical', 'warning')),
  status text not null default 'open' check (status in ('open', 'resolved')),
  title text not null,
  started_at timestamptz not null default now(),
  resolved_at timestamptz
);

create index if not exists incidents_service_status_idx
  on public.incidents (service_id, status);

alter table public.services enable row level security;
alter table public.health_logs enable row level security;
alter table public.incidents enable row level security;

drop policy if exists "public read services" on public.services;
drop policy if exists "public read health logs" on public.health_logs;
drop policy if exists "public read incidents" on public.incidents;

create policy "public read services"
  on public.services for select using (true);
create policy "public read health logs"
  on public.health_logs for select using (true);
create policy "public read incidents"
  on public.incidents for select using (true);

-- Realtime websocket streams for the dashboard.
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and tablename = 'services'
  ) then
    alter publication supabase_realtime add table public.services;
  end if;

  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and tablename = 'incidents'
  ) then
    alter publication supabase_realtime add table public.incidents;
  end if;

  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and tablename = 'health_logs'
  ) then
    alter publication supabase_realtime add table public.health_logs;
  end if;
end $$;
